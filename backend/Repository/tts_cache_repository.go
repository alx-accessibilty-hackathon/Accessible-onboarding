package repository

import (
	"context"
	"errors"

	domain "bridge/Domain"
	sqlc "bridge/Repository/sqlc"

	"github.com/jackc/pgx/v5"
	"github.com/jackc/pgx/v5/pgxpool"
)

// TTSCacheRepository keeps read-aloud audio of fixed interface text, so a text-to-speech
// provider is paid once per clip, whichever server or device asks again.
// Table: tts_cache. Queries: queries/tts_cache.sql.
type TTSCacheRepository struct {
	DB *pgxpool.Pool
	Q  *sqlc.Queries // generated by sqlc
}

var _ domain.TTSCacheRepositoryI = (*TTSCacheRepository)(nil)

func NewTTSCacheRepo(db *pgxpool.Pool) *TTSCacheRepository {
	return &TTSCacheRepository{
		DB: db,
		Q:  sqlc.New(db),
	}
}

func (r *TTSCacheRepository) GetAudio(ctx context.Context, key string) ([]byte, error) {
	audio, err := r.Q.GetTTSAudio(ctx, key)
	if errors.Is(err, pgx.ErrNoRows) {
		return nil, domain.ErrNotFound
	}
	if err != nil {
		return nil, err
	}
	return audio, nil
}

// Clear forgets every clip (`bridge tts-clear`) and returns how many there were.
func (r *TTSCacheRepository) Clear(ctx context.Context) (int64, error) {
	return r.Q.DeleteAllTTSAudio(ctx)
}

func (r *TTSCacheRepository) PutAudio(ctx context.Context, clip *domain.TTSClip) error {
	mime := clip.MimeType
	if mime == "" {
		mime = "audio/mpeg"
	}
	return r.Q.PutTTSAudio(ctx, sqlc.PutTTSAudioParams{
		CacheKey: clip.Key,
		Provider: clip.Provider,
		Voice:    clip.Voice,
		Language: clip.Language,
		Text:     clip.Text,
		MimeType: mime,
		Audio:    clip.Audio,
	})
}
