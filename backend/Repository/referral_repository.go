package repository

import (
	"context"
	"errors"

	domain "bridge/Domain"
	sqlc "bridge/Repository/sqlc"

	"github.com/google/uuid"
	"github.com/jackc/pgx/v5"
	"github.com/jackc/pgx/v5/pgxpool"
)

// ReferralRepository is the referral queue of a referral organisation (R7): referrals with
// the learner's name, contact and language. Tables: referrals, learners.
// Queries: queries/referrals.sql.
type ReferralRepository struct {
	DB *pgxpool.Pool
	Q  *sqlc.Queries // generated by sqlc
}

var _ domain.ReferralRepositoryI = (*ReferralRepository)(nil)

func NewReferralRepo(db *pgxpool.Pool) *ReferralRepository {
	return &ReferralRepository{
		DB: db,
		Q:  sqlc.New(db),
	}
}

func (r *ReferralRepository) ListByPartner(ctx context.Context, partnerID uuid.UUID) ([]*domain.PartnerReferral, error) {
	rows, err := r.Q.ListReferralsByPartner(ctx, partnerID)
	if err != nil {
		return nil, err
	}
	out := make([]*domain.PartnerReferral, 0, len(rows))
	for _, row := range rows {
		out = append(out, toPartnerReferral(sqlc.GetPartnerReferralRow(row)))
	}
	return out, nil
}

func (r *ReferralRepository) UpdateStatus(ctx context.Context, id, partnerID uuid.UUID, status string) (*domain.PartnerReferral, error) {
	n, err := r.Q.UpdateReferralStatus(ctx, sqlc.UpdateReferralStatusParams{ID: id, PartnerID: partnerID, Status: status})
	if err != nil {
		return nil, err
	}
	if n == 0 {
		return nil, domain.ErrNotFound // missing, or another partner's (Q7)
	}
	row, err := r.Q.GetPartnerReferral(ctx, sqlc.GetPartnerReferralParams{ID: id, PartnerID: partnerID})
	if errors.Is(err, pgx.ErrNoRows) {
		return nil, domain.ErrNotFound
	}
	if err != nil {
		return nil, err
	}
	return toPartnerReferral(row), nil
}

func toPartnerReferral(r sqlc.GetPartnerReferralRow) *domain.PartnerReferral {
	return &domain.PartnerReferral{
		Referral: &domain.Referral{
			ID:                r.ID,
			LearnerID:         r.LearnerID,
			PartnerID:         r.PartnerID,
			ContactPreference: r.ContactPreference,
			Status:            r.Status,
			CreatedAt:         r.CreatedAt,
			UpdatedAt:         r.UpdatedAt,
		},
		Learner: &domain.Learner{
			ID:            r.LearnerID,
			FullName:      deref(r.FullName),
			PreferredName: deref(r.PreferredName),
			ContactMethod: deref(r.ContactMethod),
			PhoneE164:     deref(r.PhoneE164),
			Language:      r.Language,
		},
	}
}
