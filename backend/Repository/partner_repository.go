package repository

import (
	"context"
	"encoding/json"
	"errors"
	"time"

	domain "bridge/Domain"
	sqlc "bridge/Repository/sqlc"

	"github.com/google/uuid"
	"github.com/jackc/pgx/v5"
	"github.com/jackc/pgx/v5/pgxpool"
)

// PartnerRepository reads partners (platforms like Savanna, referral organisations like AAAPD)
// and employers. Tables: partners, employers. Queries: queries/partners.sql.
//
// This file is the example of the pattern: call the generated sqlc method (r.Q.…),
// turn "no rows" into domain.ErrNotFound, and map the generated row to a domain entity.
type PartnerRepository struct {
	DB *pgxpool.Pool // for transactions: tx, _ := r.DB.Begin(ctx); q := r.Q.WithTx(tx)
	Q  *sqlc.Queries // generated by sqlc
}

// Compile-time check that PartnerRepository implements the domain interface.
var _ domain.PartnerRepositoryI = (*PartnerRepository)(nil)
var _ domain.PartnerCreatorI = (*PartnerRepository)(nil)

func NewPartnerRepo(db *pgxpool.Pool) *PartnerRepository {
	return &PartnerRepository{
		DB: db,
		Q:  sqlc.New(db),
	}
}

func (r *PartnerRepository) GetByPublishableKey(ctx context.Context, key string) (*domain.Partner, error) {
	row, err := r.Q.GetPartnerByPublishableKey(ctx, key)
	if errors.Is(err, pgx.ErrNoRows) {
		return nil, domain.ErrNotFound
	}
	if err != nil {
		return nil, err
	}

	var cfg map[string]any
	if len(row.Config) > 0 {
		if err := json.Unmarshal(row.Config, &cfg); err != nil {
			return nil, err
		}
	}

	return &domain.Partner{
		ID:             row.ID,
		Slug:           row.Slug,
		Name:           row.Name,
		Kind:           row.Kind,
		PublishableKey: row.PublishableKey,
		AllowedOrigins: row.AllowedOrigins,
		ClientID:       deref(row.ClientID),
		Config:         cfg,
		CreatedAt:      row.CreatedAt,
	}, nil
}

func (r *PartnerRepository) ListReferralPartners(ctx context.Context) ([]*domain.Partner, error) {
	rows, err := r.Q.ListReferralPartners(ctx)
	if err != nil {
		return nil, err
	}
	partners := make([]*domain.Partner, 0, len(rows))
	for _, row := range rows {
		partners = append(partners, &domain.Partner{ID: row.ID, Name: row.Name})
	}
	return partners, nil
}

func (r *PartnerRepository) ListAllowedOrigins(ctx context.Context) ([]string, error) {
	return r.Q.ListAllowedOrigins(ctx)
}

func (r *PartnerRepository) GetByID(ctx context.Context, id uuid.UUID) (*domain.Partner, error) {
	row, err := r.Q.GetPartnerByID(ctx, id)
	if errors.Is(err, pgx.ErrNoRows) {
		return nil, domain.ErrNotFound
	}
	if err != nil {
		return nil, err
	}
	return toPartner(row.ID, row.Slug, row.Name, row.Kind, row.PublishableKey, row.AllowedOrigins, row.ClientID, row.Config, row.CreatedAt)
}

func (r *PartnerRepository) GetByClientID(ctx context.Context, clientID string) (*domain.Partner, []byte, error) {
	row, err := r.Q.GetPartnerByClientID(ctx, &clientID)
	if errors.Is(err, pgx.ErrNoRows) {
		return nil, nil, domain.ErrNotFound
	}
	if err != nil {
		return nil, nil, err
	}
	p, err := toPartner(row.ID, row.Slug, row.Name, row.Kind, row.PublishableKey, row.AllowedOrigins, row.ClientID, row.Config, row.CreatedAt)
	if err != nil {
		return nil, nil, err
	}
	return p, row.ClientSecretHash, nil
}

// Create saves a self-service partner. A taken slug, key or client ID is ErrAlreadyExists.
func (r *PartnerRepository) Create(ctx context.Context, p domain.NewPartner) (*domain.Partner, error) {
	config, err := json.Marshal(p.Config)
	if err != nil {
		return nil, err
	}
	row, err := r.Q.CreatePartner(ctx, sqlc.CreatePartnerParams{
		Slug:             p.Slug,
		Name:             p.Name,
		Kind:             p.Kind,
		PublishableKey:   p.PublishableKey,
		AllowedOrigins:   p.AllowedOrigins,
		ClientID:         nilIfEmpty(p.ClientID),
		ClientSecretHash: p.SecretHash,
		Config:           config,
	})
	if hasPgCode(err, pgUniqueViolation) {
		return nil, domain.ErrAlreadyExists
	}
	if err != nil {
		return nil, err
	}
	return toPartner(row.ID, row.Slug, row.Name, row.Kind, row.PublishableKey, row.AllowedOrigins, row.ClientID, row.Config, row.CreatedAt)
}

func toPartner(id uuid.UUID, slug, name, kind, key string, origins []string, clientID *string, config json.RawMessage, createdAt time.Time) (*domain.Partner, error) {
	var cfg map[string]any
	if len(config) > 0 {
		if err := json.Unmarshal(config, &cfg); err != nil {
			return nil, err
		}
	}
	return &domain.Partner{
		ID:             id,
		Slug:           slug,
		Name:           name,
		Kind:           kind,
		PublishableKey: key,
		AllowedOrigins: origins,
		ClientID:       deref(clientID),
		Config:         cfg,
		CreatedAt:      createdAt,
	}, nil
}
