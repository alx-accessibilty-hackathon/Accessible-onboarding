func (r *SessionRepository) CreateOutboxMessage(ctx context.Context, msg *domain.OutboxMessage) (*domain.OutboxMessage, error) {
	row, err := r.Q.CreateOutboxMessage(ctx, sqlc.CreateOutboxMessageParams{
		Channel:   msg.Channel,
		Recipient: msg.Recipient,
		Body:      msg.Body,
		Status:    msg.Status,
		Provider:  msg.Provider,
	})
	if err != nil {
		return nil, err
	}
	return &domain.OutboxMessage{
		ID:        row.ID,
		Channel:   row.Channel,
		Recipient: row.Recipient,
		Body:      row.Body,
		Status:    row.Status,
		Provider:  row.Provider,
		Error:     row.Error,
		CreatedAt: row.CreatedAt,
		SentAt:    row.SentAt,
	}, nil
}

// MarkOutboxMessage records what the SMS provider said: "sent" (accepted) or "failed" (errText).
func (r *SessionRepository) MarkOutboxMessage(ctx context.Context, id uuid.UUID, status, provider string, errText *string) error {
	return r.Q.MarkOutboxMessage(ctx, sqlc.MarkOutboxMessageParams{
		ID: id, Status: status, Provider: &provider, Error: errText,
	})
}

func toDomainAuthSession(s *sqlc.AuthSession) *domain.AuthSession {
	return &domain.AuthSession{
		ID:          s.ID,
		SubjectType: s.SubjectType,
		SubjectID:   s.SubjectID,
		TokenHash:   s.TokenHash,
		Scopes:      s.Scopes,
		ActingFor:   s.ActingFor,
		ExpiresAt:   s.ExpiresAt,
		RevokedAt:   s.RevokedAt,
	}
}

func toDomainResumeToken(r *sqlc.ResumeToken) *domain.ResumeToken {
	return &domain.ResumeToken{
		ID:             r.ID,
		RegistrationID: r.RegistrationID,
		TokenHash:      r.TokenHash,
		CodeHash:       r.CodeHash,
		FailedAttempts: int(r.FailedAttempts),
		ExpiresAt:      r.ExpiresAt,
		UsedAt:         r.UsedAt,
		CreatedAt:      r.CreatedAt,
	}
}

func toDomainVerificationCode(v *sqlc.VerificationCode) *domain.VerificationCode {
	return &domain.VerificationCode{
		ID:             v.ID,
		PhoneE164:      v.PhoneE164,
		Purpose:        v.Purpose,
		CodeHash:       v.CodeHash,
		LearnerID:      v.LearnerID,
		FailedAttempts: int(v.FailedAttempts),
		ExpiresAt:      v.ExpiresAt,
		UsedAt:         v.UsedAt,
		CreatedAt:      v.CreatedAt,
	}
}

func (r *SessionRepository) ListOutboxMessages(ctx context.Context) ([]*domain.OutboxMessage, error) {
	rows, err := r.Q.ListQueuedOutboxMessages(ctx)
	if err != nil {
		return nil, err
	}
	out := make([]*domain.OutboxMessage, 0, len(rows))
	for _, m := range rows {
		out = append(out, &domain.OutboxMessage{
			ID: m.ID, Channel: m.Channel, Recipient: m.Recipient, Body: m.Body, Status: m.Status,
			Provider: m.Provider, Error: m.Error, CreatedAt: m.CreatedAt, SentAt: m.SentAt,
		})
	}
	return out, nil
}
