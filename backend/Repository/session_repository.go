// SessionRepository stores sign-in sessions for learners, staff and partner servers.
// Also handles resume tokens, verification codes and outbox messages.
type SessionRepository struct {
	DB *pgxpool.Pool // for transactions
	Q  *sqlc.Queries // generated by sqlc
}

var _ domain.SessionRepositoryI = (*SessionRepository)(nil)

func NewSessionRepo(db *pgxpool.Pool) *SessionRepository {
	return &SessionRepository{
		DB: db,
		Q:  sqlc.New(db),
	}
}

func (r *SessionRepository) CreateAuthSession(ctx context.Context, session *domain.AuthSession) (*domain.AuthSession, error) {
	scopes := session.Scopes
	if scopes == nil {
		scopes = []string{} // the column is NOT NULL; a nil slice would be sent as NULL
	}
	row, err := r.Q.CreateAuthSession(ctx, sqlc.CreateAuthSessionParams{
		SubjectType: session.SubjectType,
		SubjectID:   session.SubjectID,
		TokenHash:   session.TokenHash,
		Scopes:      scopes,
		ActingFor:   session.ActingFor,
		ExpiresAt:   session.ExpiresAt,
	})
	if err != nil {
		return nil, err
	}
	return toDomainAuthSession(&row), nil
}

func (r *SessionRepository) GetAuthSessionByTokenHash(ctx context.Context, tokenHash []byte) (*domain.AuthSession, error) {
	row, err := r.Q.GetAuthSessionByTokenHash(ctx, tokenHash)
	if errors.Is(err, pgx.ErrNoRows) {
		return nil, domain.ErrNotFound
	}
	if err != nil {
		return nil, err
	}
	return toDomainAuthSession(&row), nil
}

func (r *SessionRepository) RevokeAuthSession(ctx context.Context, id uuid.UUID) error {
	return r.Q.RevokeAuthSession(ctx, id)
}

func (r *SessionRepository) TouchAuthSession(ctx context.Context, id uuid.UUID, newExpiry *time.Time) error {
	return r.Q.TouchAuthSession(ctx, sqlc.TouchAuthSessionParams{ID: id, NewExpiresAt: newExpiry})
}

