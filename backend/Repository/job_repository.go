package repository

import (
	sqlc "bridge/Repository/sqlc"

	"github.com/jackc/pgx/v5/pgxpool"
)

// JobRepository handles job postings and their accommodation codes.
// Table: jobs.
type JobRepository struct {
	DB *pgxpool.Pool // for transactions
	Q  *sqlc.Queries // generated by sqlc
}

func NewJobRepo(db *pgxpool.Pool) *JobRepository {
	return &JobRepository{
		DB: db,
		Q:  sqlc.New(db),
	}
}
