package repository

import (
	"context"
	"errors"

	domain "bridge/Domain"
	sqlc "bridge/Repository/sqlc"

	"github.com/google/uuid"
	"github.com/jackc/pgx/v5"
	"github.com/jackc/pgx/v5/pgxpool"
)

// JobRepository handles job postings and their accommodation codes.
// Tables: jobs (joined with employers for the name). Queries: queries/jobs.sql.
type JobRepository struct {
	DB *pgxpool.Pool // for transactions
	Q  *sqlc.Queries // generated by sqlc
}

var _ domain.JobRepositoryI = (*JobRepository)(nil)

func NewJobRepo(db *pgxpool.Pool) *JobRepository {
	return &JobRepository{
		DB: db,
		Q:  sqlc.New(db),
	}
}

func (r *JobRepository) ListPublished(ctx context.Context, limit int, after *domain.JobCursor) ([]*domain.Job, error) {
	params := sqlc.ListPublishedJobsParams{RowLimit: int32(limit)}
	if after != nil {
		params.AfterPublishedAt = &after.PublishedAt
		params.AfterID = &after.ID
	}
	rows, err := r.Q.ListPublishedJobs(ctx, params)
	if err != nil {
		return nil, err
	}
	jobs := make([]*domain.Job, 0, len(rows))
	for _, row := range rows {
		jobs = append(jobs, toJob(sqlc.GetPublishedJobRow(row)))
	}
	return jobs, nil
}

func (r *JobRepository) GetPublished(ctx context.Context, id uuid.UUID) (*domain.Job, error) {
	row, err := r.Q.GetPublishedJob(ctx, id)
	if errors.Is(err, pgx.ErrNoRows) {
		return nil, domain.ErrNotFound
	}
	if err != nil {
		return nil, err
	}
	return toJob(row), nil
}

func (r *JobRepository) ListByEmployer(ctx context.Context, employerID uuid.UUID) ([]*domain.Job, error) {
	rows, err := r.Q.ListJobsByEmployer(ctx, &employerID)
	if err != nil {
		return nil, err
	}
	jobs := make([]*domain.Job, 0, len(rows))
	for _, row := range rows {
		jobs = append(jobs, toJob(sqlc.GetPublishedJobRow(row)))
	}
	return jobs, nil
}

func (r *JobRepository) Create(ctx context.Context, job *domain.Job) (*domain.Job, error) {
	accommodations := job.Accommodations
	if accommodations == nil {
		accommodations = []string{} // the column is NOT NULL
	}
	row, err := r.Q.CreateJob(ctx, sqlc.CreateJobParams{
		EmployerID:     job.EmployerID,
		Source:         job.Source,
		Title:          job.Title,
		Description:    job.Description,
		LocationType:   job.LocationType,
		LocationText:   nilIfEmpty(job.LocationText),
		WorkHours:      nilIfEmpty(job.WorkHours),
		EmploymentType: job.EmploymentType,
		Accommodations: accommodations,
	})
	if hasPgCode(err, pgForeignKeyViolation) {
		return nil, domain.ErrNotFound // the employer doesn't exist
	}
	if err != nil {
		return nil, err
	}
	created := toJobWithoutEmployer(row)
	created.EmployerName = job.EmployerName
	return created, nil
}

func (r *JobRepository) Publish(ctx context.Context, id, employerID uuid.UUID) (*domain.Job, error) {
	row, err := r.Q.PublishJob(ctx, sqlc.PublishJobParams{ID: id, EmployerID: &employerID})
	if errors.Is(err, pgx.ErrNoRows) {
		return nil, domain.ErrNotFound // missing, another employer's (Q7), or closed
	}
	if err != nil {
		return nil, err
	}
	return toJobWithoutEmployer(sqlc.CreateJobRow(row)), nil
}
