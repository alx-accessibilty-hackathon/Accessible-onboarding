package repository

import (
	"context"
	"errors"

	domain "bridge/Domain"
	sqlc "bridge/Repository/sqlc"

	"github.com/google/uuid"
	"github.com/jackc/pgx/v5"
	"github.com/jackc/pgx/v5/pgxpool"
)

// LearnerRepository handles learners, their ID evidence and referrals.
// Tables: learners, identity_evidence, referrals. Queries: queries/registrations.sql.
// (Learners are created and their profile is filled by RegistrationRepository.Start and
// SubmitTx, because those write several tables in one transaction.)
type LearnerRepository struct {
	DB *pgxpool.Pool // for transactions
	Q  *sqlc.Queries // generated by sqlc
}

var _ domain.LearnerRepositoryI = (*LearnerRepository)(nil)

func NewLearnerRepo(db *pgxpool.Pool) *LearnerRepository {
	return &LearnerRepository{
		DB: db,
		Q:  sqlc.New(db),
	}
}

func (r *LearnerRepository) Get(ctx context.Context, id uuid.UUID) (*domain.Learner, error) {
	row, err := r.Q.GetLearner(ctx, id)
	if errors.Is(err, pgx.ErrNoRows) {
		return nil, domain.ErrNotFound
	}
	if err != nil {
		return nil, err
	}
	return toLearner(row), nil
}

func (r *LearnerRepository) UpdatePreferences(ctx context.Context, id uuid.UUID, language *string, simple *bool) error {
	n, err := r.Q.UpdateLearnerPreferences(ctx, sqlc.UpdateLearnerPreferencesParams{
		ID:         id,
		Language:   language,
		SimpleMode: simple,
	})
	if err != nil {
		return err
	}
	if n == 0 {
		return domain.ErrNotFound
	}
	return nil
}

func (r *LearnerRepository) GetLatestReferral(ctx context.Context, learnerID uuid.UUID) (*domain.Referral, error) {
	row, err := r.Q.GetLatestReferralByLearner(ctx, learnerID)
	if errors.Is(err, pgx.ErrNoRows) {
		return nil, domain.ErrNotFound
	}
	if err != nil {
		return nil, err
	}
	return toReferral(row), nil
}
