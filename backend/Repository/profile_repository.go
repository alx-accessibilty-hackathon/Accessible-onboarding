// ProfileRepository is what /me needs: the learner's latest registration, identity evidence
// and (encrypted) support request; changing the profile; deleting the learner.
// Tables: learners, registrations, answers, identity_evidence, support_requests,
// auth_sessions, audit_log. Queries: queries/me.sql, queries/support.sql, queries/audit.sql.
type ProfileRepository struct {
	DB *pgxpool.Pool // for transactions (update and delete write several tables)
	Q  *sqlc.Queries // generated by sqlc
}

var _ domain.ProfileRepositoryI = (*ProfileRepository)(nil)

func NewProfileRepo(db *pgxpool.Pool) *ProfileRepository {
	return &ProfileRepository{
		DB: db,
		Q:  sqlc.New(db),
	}
}

func (r *ProfileRepository) GetLatestRegistration(ctx context.Context, learnerID uuid.UUID) (*domain.Registration, error) {
	row, err := r.Q.GetLatestRegistrationByLearner(ctx, learnerID)
	if errors.Is(err, pgx.ErrNoRows) {
		return nil, domain.ErrNotFound
	}
	if err != nil {
		return nil, err
	}
	return toRegistration(row), nil
}

func (r *ProfileRepository) GetLatestIdentityEvidence(ctx context.Context, learnerID uuid.UUID) (*domain.IdentityEvidence, error) {
	row, err := r.Q.GetLatestIdentityEvidenceByLearner(ctx, learnerID)
	if errors.Is(err, pgx.ErrNoRows) {
		return nil, domain.ErrNotFound
	}
	if err != nil {
		return nil, err
	}
	return toIdentityEvidence(row), nil
}

func (r *ProfileRepository) GetSealedSupportRequest(ctx context.Context, learnerID uuid.UUID) (*domain.SealedSupportRequest, error) {
	row, err := r.Q.GetSupportRequestByLearner(ctx, learnerID)
	if errors.Is(err, pgx.ErrNoRows) {
		return nil, domain.ErrNotFound
	}
	if err != nil {
		return nil, err
	}
	return &domain.SealedSupportRequest{
		LearnerID:      row.LearnerID,
		Nonce:          row.Nonce,
		Ciphertext:     row.Ciphertext,
		ShareCourses:   row.ShareCourses,
		ShareEmployers: row.ShareEmployers,
		UpdatedAt:      row.UpdatedAt,
	}, nil
}

// UpdateProfile writes the whole editable profile in one transaction. When the phone number
// is cleared (contact by partner or none), the phone answer saved at sign-up is deleted too.
func (r *ProfileRepository) UpdateProfile(ctx context.Context, l *domain.Learner) (*domain.Learner, error) {
	tx, err := r.DB.Begin(ctx)
	if err != nil {
		return nil, err
	}
	defer tx.Rollback(ctx) // does nothing after Commit
	q := r.Q.WithTx(tx)

	row, err := q.UpdateLearnerContact(ctx, sqlc.UpdateLearnerContactParams{
		ID:            l.ID,
		FullName:      nilIfEmpty(l.FullName),
		PreferredName: nilIfEmpty(l.PreferredName),
		ContactMethod: nilIfEmpty(l.ContactMethod),
		PhoneE164:     nilIfEmpty(l.PhoneE164),
		Dob:           l.DOB,
		DobCalendar:   nilIfEmpty(l.DOBCalendar),
		Language:      l.Language,
		SimpleMode:    l.SimpleMode,
	})
	if errors.Is(err, pgx.ErrNoRows) {
		return nil, domain.ErrNotFound
	}
	if err != nil {
		return nil, err
	}
	if l.PhoneE164 == "" {
		if err := q.DeletePhoneAnswersByLearner(ctx, l.ID); err != nil {
			return nil, err
		}
	}
	if err := tx.Commit(ctx); err != nil {
		return nil, err
	}
	return toLearner(row), nil
}

// DeleteLearner deletes the learner (everything else about them cascades), their sessions,
// and writes the audit entry, all or nothing.
func (r *ProfileRepository) DeleteLearner(ctx context.Context, learnerID uuid.UUID, audit *domain.AuditEntry) error {
	tx, err := r.DB.Begin(ctx)
	if err != nil {
		return err
	}
	defer tx.Rollback(ctx) // does nothing after Commit
	q := r.Q.WithTx(tx)

	n, err := q.DeleteLearner(ctx, learnerID)
	if err != nil {
		return err
	}
	if n == 0 {
		return domain.ErrNotFound
	}
	if err := q.DeleteLearnerSessions(ctx, learnerID); err != nil {
		return err
	}
	if audit != nil {
		if err := createAuditLog(ctx, q, audit); err != nil {
			return err
		}
	}
	return tx.Commit(ctx)
}

// createAuditLog writes one audit row with q (a transaction or the pool).
func createAuditLog(ctx context.Context, q *sqlc.Queries, e *domain.AuditEntry) error {
	meta := json.RawMessage(`{}`)
	if len(e.Meta) > 0 {
		b, err := json.Marshal(e.Meta)
		if err != nil {
			return err
		}
		meta = b
	}
	return q.CreateAuditLog(ctx, sqlc.CreateAuditLogParams{
		ActorType:  e.ActorType,
		ActorID:    e.ActorID,
		Action:     e.Action,
		TargetType: nilIfEmpty(e.TargetType),
		TargetID:   e.TargetID,
		Meta:       meta,
	})
}
