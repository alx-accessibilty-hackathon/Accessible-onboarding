package repository

import (
	"context"
	"errors"

	domain "bridge/Domain"
	sqlc "bridge/Repository/sqlc"

	"github.com/google/uuid"
	"github.com/jackc/pgx/v5"
	"github.com/jackc/pgx/v5/pgxpool"
)

// RegistrationRepository handles registrations and their answers
// (each answer has a version number for the "another device saved first" check).
// Tables: registrations, answers.
type RegistrationRepository struct {
	DB *pgxpool.Pool // for transactions (submit writes several tables at once)
	Q  *sqlc.Queries // generated by sqlc
}

var _ domain.RegistrationRepositoryI = (*RegistrationRepository)(nil)

func NewRegistrationRepo(db *pgxpool.Pool) *RegistrationRepository {
	return &RegistrationRepository{
		DB: db,
		Q:  sqlc.New(db),
	}
}

func (r *RegistrationRepository) GetRegistrationByID(ctx context.Context, id uuid.UUID) (*domain.Registration, error) {
	row, err := r.Q.GetRegistrationByID(ctx, id)
	if errors.Is(err, pgx.ErrNoRows) {
		return nil, domain.ErrNotFound
	}
	if err != nil {
		return nil, err
	}

	return &domain.Registration{
		ID:            row.ID,
		LearnerID:     row.LearnerID,
		FlowID:        row.FlowID,
		FlowVersion:   int(row.FlowVersion),
		Status:        row.Status,
		CurrentStep:   deref(row.CurrentStep),
		ActingStaffID: row.ActingStaffID,
		CreatedAt:     row.CreatedAt,
		UpdatedAt:     row.UpdatedAt,
		SubmittedAt:   row.SubmittedAt,
	}, nil
}

func (r *RegistrationRepository) GetAnswer(ctx context.Context, registrationID uuid.UUID, questionID string) (*domain.Answer, error) {
	row, err := r.Q.GetAnswer(ctx, sqlc.GetAnswerParams{
		RegistrationID: registrationID,
		QuestionID:     questionID,
	})
	if errors.Is(err, pgx.ErrNoRows) {
		return nil, domain.ErrNotFound
	}
	if err != nil {
		return nil, err
	}

	return &domain.Answer{
		RegistrationID: row.RegistrationID,
		QuestionID:     row.QuestionID,
		Value:          row.Value,
		InputMethod:    row.InputMethod,
		Version:        int(row.Version),
		UpdatedAt:      row.UpdatedAt,
	}, nil
}

func (r *RegistrationRepository) ListAnswersByRegistrationID(ctx context.Context, registrationID uuid.UUID) ([]*domain.Answer, error) {
	rows, err := r.Q.ListAnswersByRegistrationID(ctx, registrationID)
	if err != nil {
		return nil, err
	}

	answers := make([]*domain.Answer, 0, len(rows))
	for _, row := range rows {
		answers = append(answers, &domain.Answer{
			RegistrationID: row.RegistrationID,
			QuestionID:     row.QuestionID,
			Value:          row.Value,
			InputMethod:    row.InputMethod,
			Version:        int(row.Version),
			UpdatedAt:      row.UpdatedAt,
		})
	}
	return answers, nil
}
