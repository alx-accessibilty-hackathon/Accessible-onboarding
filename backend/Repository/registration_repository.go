package repository

import (
	"context"
	"errors"

	domain "bridge/Domain"
	sqlc "bridge/Repository/sqlc"

	"github.com/google/uuid"
	"github.com/jackc/pgx/v5"
	"github.com/jackc/pgx/v5/pgxpool"
)

// RegistrationRepository handles registrations and their answers
// (each answer has a version number for the "another device saved first" check).
// Tables: registrations, answers (and learners, identity_evidence, referrals on start and submit).
// Queries: queries/registrations.sql.
type RegistrationRepository struct {
	DB *pgxpool.Pool // for transactions (start and submit write several tables at once)
	Q  *sqlc.Queries // generated by sqlc
}

var _ domain.RegistrationRepositoryI = (*RegistrationRepository)(nil)

func NewRegistrationRepo(db *pgxpool.Pool) *RegistrationRepository {
	return &RegistrationRepository{
		DB: db,
		Q:  sqlc.New(db),
	}
}

// Start creates the draft learner and the registration together: both or neither.
func (r *RegistrationRepository) Start(ctx context.Context, learner *domain.Learner, reg *domain.Registration) (*domain.Learner, *domain.Registration, error) {
	tx, err := r.DB.Begin(ctx)
	if err != nil {
		return nil, nil, err
	}
	defer tx.Rollback(ctx) // does nothing after Commit
	q := r.Q.WithTx(tx)

	lrow, err := q.CreateLearner(ctx, sqlc.CreateLearnerParams{
		PartnerID:  learner.PartnerID,
		Language:   learner.Language,
		SimpleMode: learner.SimpleMode,
	})
	if err != nil {
		return nil, nil, err
	}
	rrow, err := q.CreateRegistration(ctx, sqlc.CreateRegistrationParams{
		LearnerID:   lrow.ID,
		FlowID:      reg.FlowID,
		FlowVersion: int32(reg.FlowVersion),
		CurrentStep: reg.CurrentStep,
	})
	if err != nil {
		return nil, nil, err
	}
	if err := tx.Commit(ctx); err != nil {
		return nil, nil, err
	}
	return toLearner(lrow), toRegistration(rrow), nil
}

func (r *RegistrationRepository) Get(ctx context.Context, id uuid.UUID) (*domain.Registration, error) {
	row, err := r.Q.GetRegistration(ctx, id)
	if errors.Is(err, pgx.ErrNoRows) {
		return nil, domain.ErrNotFound
	}
	if err != nil {
		return nil, err
	}
	return toRegistration(row), nil
}

func (r *RegistrationRepository) UpdateProgress(ctx context.Context, id uuid.UUID, step string) error {
	n, err := r.Q.UpdateRegistrationProgress(ctx, sqlc.UpdateRegistrationProgressParams{ID: id, CurrentStep: step})
	if err != nil {
		return err
	}
	if n == 0 {
		return domain.ErrNotFound
	}
	return nil
}

func (r *RegistrationRepository) ListAnswers(ctx context.Context, regID uuid.UUID) ([]*domain.Answer, error) {
	rows, err := r.Q.ListAnswers(ctx, regID)
	if err != nil {
		return nil, err
	}
	answers := make([]*domain.Answer, 0, len(rows))
	for _, row := range rows {
		answers = append(answers, toAnswer(row))
	}
	return answers, nil
}

// SaveAnswerIfVersion runs the "save only if nobody saved in between" query (R15).
// No row back means the saved version is newer than baseVersion: it then reads the saved
// answer and returns it inside a *domain.ConflictError.
func (r *RegistrationRepository) SaveAnswerIfVersion(ctx context.Context, a *domain.Answer, baseVersion int) (*domain.Answer, error) {
	row, err := r.Q.SaveAnswerIfVersion(ctx, sqlc.SaveAnswerIfVersionParams{
		RegistrationID: a.RegistrationID,
		QuestionID:     a.QuestionID,
		Value:          a.Value,
		InputMethod:    a.InputMethod,
		BaseVersion:    int32(baseVersion),
	})
	if err == nil {
		return toAnswer(row), nil
	}
	if !errors.Is(err, pgx.ErrNoRows) {
		if hasPgCode(err, pgForeignKeyViolation) {
			return nil, domain.ErrNotFound // the registration was deleted
		}
		return nil, err
	}

	current, err := r.Q.GetAnswer(ctx, sqlc.GetAnswerParams{RegistrationID: a.RegistrationID, QuestionID: a.QuestionID})
	if err != nil {
		return nil, err
	}
	return nil, &domain.ConflictError{Current: toAnswer(current)}
}

// SubmitTx does every write of a submit in one transaction, so a failure leaves the
// registration a draft with nothing half-written.
func (r *RegistrationRepository) SubmitTx(ctx context.Context, regID uuid.UUID, profile *domain.Learner, ev *domain.IdentityEvidence, ref *domain.Referral) (*domain.SubmitResult, error) {
	tx, err := r.DB.Begin(ctx)
	if err != nil {
		return nil, err
	}
	defer tx.Rollback(ctx) // does nothing after Commit
	q := r.Q.WithTx(tx)

	// First, so a second submit at the same moment waits here and then finds no draft.
	n, err := q.MarkRegistrationSubmitted(ctx, regID)
	if err != nil {
		return nil, err
	}
	if n == 0 {
		return nil, domain.ErrAlreadySubmitted
	}

	lrow, err := q.UpdateLearnerProfile(ctx, sqlc.UpdateLearnerProfileParams{
		ID:            profile.ID,
		FullName:      nilIfEmpty(profile.FullName),
		PreferredName: nilIfEmpty(profile.PreferredName),
		ContactMethod: nilIfEmpty(profile.ContactMethod),
		PhoneE164:     nilIfEmpty(profile.PhoneE164),
		Dob:           profile.DOB,
		DobCalendar:   nilIfEmpty(profile.DOBCalendar),
	})
	if errors.Is(err, pgx.ErrNoRows) {
		return nil, domain.ErrNotFound
	}
	if err != nil {
		return nil, err
	}

	evRow, err := q.CreateIdentityEvidence(ctx, sqlc.CreateIdentityEvidenceParams{
		LearnerID: profile.ID,
		Route:     ev.Route,
		DocType:   nilIfEmpty(ev.DocType),
		Last4:     nilIfEmpty(ev.Last4),
		Level:     ev.Level,
	})
	if err != nil {
		return nil, err
	}

	result := &domain.SubmitResult{Learner: toLearner(lrow), Evidence: toIdentityEvidence(evRow)}
	if ref != nil {
		refRow, err := q.CreateReferral(ctx, sqlc.CreateReferralParams{
			LearnerID:         profile.ID,
			PartnerID:         ref.PartnerID,
			ContactPreference: ref.ContactPreference,
		})
		if hasPgCode(err, pgForeignKeyViolation) {
			return nil, domain.NewValidationError("referral_partner", "invalid_choice")
		}
		if err != nil {
			return nil, err
		}
		result.Referral = toReferral(refRow)
	}

	if err := tx.Commit(ctx); err != nil {
		return nil, err
	}
	return result, nil
}
