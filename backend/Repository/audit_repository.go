package repository

import (
	"context"

	domain "bridge/Domain"
	sqlc "bridge/Repository/sqlc"

	"github.com/jackc/pgx/v5/pgxpool"
)

// AuditRepository writes the audit log (who read or deleted personal data).
// Table: audit_log. Queries: queries/audit.sql.
type AuditRepository struct {
	DB *pgxpool.Pool
	Q  *sqlc.Queries // generated by sqlc
}

var _ domain.AuditRepositoryI = (*AuditRepository)(nil)

func NewAuditRepo(db *pgxpool.Pool) *AuditRepository {
	return &AuditRepository{
		DB: db,
		Q:  sqlc.New(db),
	}
}

func (r *AuditRepository) Log(ctx context.Context, e *domain.AuditEntry) error {
	return createAuditLog(ctx, r.Q, e)
}
