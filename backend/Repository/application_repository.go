package repository

import (
	"context"

	domain "bridge/Domain"
	sqlc "bridge/Repository/sqlc"

	"github.com/google/uuid"
	"github.com/jackc/pgx/v5/pgxpool"
)

// ApplicationRepository handles job applications.
// Table: applications. Queries: queries/applications.sql.
type ApplicationRepository struct {
	DB *pgxpool.Pool // for transactions
	Q  *sqlc.Queries // generated by sqlc
}

var (
	_ domain.ApplicationRepositoryI         = (*ApplicationRepository)(nil)
	_ domain.EmployerApplicationRepositoryI = (*ApplicationRepository)(nil)
)

func NewApplicationRepo(db *pgxpool.Pool) *ApplicationRepository {
	return &ApplicationRepository{
		DB: db,
		Q:  sqlc.New(db),
	}
}

func (r *ApplicationRepository) Create(ctx context.Context, app *domain.Application) (*domain.Application, error) {
	row, err := r.Q.CreateApplication(ctx, sqlc.CreateApplicationParams{
		JobID:         app.JobID,
		LearnerID:     app.LearnerID,
		Answers:       app.Answers,
		AttachSupport: app.AttachSupport,
	})
	switch {
	case hasPgCode(err, pgUniqueViolation):
		return nil, domain.ErrAlreadyExists // UNIQUE (job_id, learner_id): one application per job
	case hasPgCode(err, pgForeignKeyViolation):
		return nil, domain.ErrNotFound // the job or the learner was deleted
	case err != nil:
		return nil, err
	}
	return toApplication(row), nil
}

// ListForEmployerJob returns the applications to a job of this employer, newest first. The
// support request is included (still encrypted) only when the applicant attached it.
func (r *ApplicationRepository) ListForEmployerJob(ctx context.Context, jobID, employerID uuid.UUID) ([]*domain.EmployerApplication, error) {
	rows, err := r.Q.ListApplicationsForEmployerJob(ctx, sqlc.ListApplicationsForEmployerJobParams{JobID: jobID, EmployerID: &employerID})
	if err != nil {
		return nil, err
	}
	out := make([]*domain.EmployerApplication, 0, len(rows))
	for _, row := range rows {
		app := &domain.EmployerApplication{
			Application: &domain.Application{
				ID:            row.ID,
				JobID:         row.JobID,
				LearnerID:     row.LearnerID,
				Answers:       row.Answers,
				AttachSupport: row.AttachSupport,
				Status:        row.Status,
				CreatedAt:     row.CreatedAt,
			},
			Applicant: &domain.Learner{
				ID:            row.LearnerID,
				FullName:      deref(row.FullName),
				PreferredName: deref(row.PreferredName),
				ContactMethod: deref(row.ContactMethod),
				PhoneE164:     deref(row.PhoneE164),
				Language:      row.Language,
			},
		}
		if row.AttachSupport && len(row.SupportCiphertext) > 0 {
			app.Sealed = &domain.SealedSupportRequest{LearnerID: row.LearnerID, Nonce: row.SupportNonce, Ciphertext: row.SupportCiphertext}
		}
		out = append(out, app)
	}
	return out, nil
}
