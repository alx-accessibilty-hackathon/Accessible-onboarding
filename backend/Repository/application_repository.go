package repository

import (
	"context"

	domain "bridge/Domain"
	sqlc "bridge/Repository/sqlc"

	"github.com/jackc/pgx/v5/pgxpool"
)

// ApplicationRepository handles job applications.
// Table: applications. Queries: queries/applications.sql.
type ApplicationRepository struct {
	DB *pgxpool.Pool // for transactions
	Q  *sqlc.Queries // generated by sqlc
}

var _ domain.ApplicationRepositoryI = (*ApplicationRepository)(nil)

func NewApplicationRepo(db *pgxpool.Pool) *ApplicationRepository {
	return &ApplicationRepository{
		DB: db,
		Q:  sqlc.New(db),
	}
}

func (r *ApplicationRepository) Create(ctx context.Context, app *domain.Application) (*domain.Application, error) {
	row, err := r.Q.CreateApplication(ctx, sqlc.CreateApplicationParams{
		JobID:         app.JobID,
		LearnerID:     app.LearnerID,
		Answers:       app.Answers,
		AttachSupport: app.AttachSupport,
	})
	switch {
	case hasPgCode(err, pgUniqueViolation):
		return nil, domain.ErrAlreadyExists // UNIQUE (job_id, learner_id): one application per job
	case hasPgCode(err, pgForeignKeyViolation):
		return nil, domain.ErrNotFound // the job or the learner was deleted
	case err != nil:
		return nil, err
	}
	return toApplication(row), nil
}
