package repository

import (
	"context"
	"errors"

	domain "bridge/Domain"
	sqlc "bridge/Repository/sqlc"

	"github.com/google/uuid"
	"github.com/jackc/pgx/v5"
	"github.com/jackc/pgx/v5/pgxpool"
)

// StaffRepository handles staff accounts (partner staff, employers, support, admin).
// Table: staff_users. Queries: queries/staff.sql.
type StaffRepository struct {
	DB *pgxpool.Pool // for transactions
	Q  *sqlc.Queries // generated by sqlc
}

var _ domain.StaffRepositoryI = (*StaffRepository)(nil)

func NewStaffRepo(db *pgxpool.Pool) *StaffRepository {
	return &StaffRepository{
		DB: db,
		Q:  sqlc.New(db),
	}
}

func (r *StaffRepository) GetByEmail(ctx context.Context, email string) (*domain.StaffUser, error) {
	row, err := r.Q.GetStaffByEmail(ctx, email)
	return toStaff(row, err)
}

func (r *StaffRepository) GetByID(ctx context.Context, id uuid.UUID) (*domain.StaffUser, error) {
	row, err := r.Q.GetStaffByID(ctx, id)
	return toStaff(row, err)
}

func toStaff(row sqlc.StaffUser, err error) (*domain.StaffUser, error) {
	if errors.Is(err, pgx.ErrNoRows) {
		return nil, domain.ErrNotFound
	}
	if err != nil {
		return nil, err
	}
	return &domain.StaffUser{
		ID:               row.ID,
		Email:            row.Email,
		PasswordHash:     row.PasswordHash,
		DisplayName:      row.DisplayName,
		Role:             row.Role,
		PartnerID:        row.PartnerID,
		EmployerID:       row.EmployerID,
		DailyAttestLimit: int(row.DailyAttestLimit),
		CreatedAt:        row.CreatedAt,
	}, nil
}
