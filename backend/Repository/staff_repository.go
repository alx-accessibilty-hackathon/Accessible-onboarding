package repository

import (
	sqlc "bridge/Repository/sqlc"

	"github.com/jackc/pgx/v5/pgxpool"
)

// StaffRepository handles staff accounts (partner staff, employers, support, admin).
// Table: staff_users.
type StaffRepository struct {
	DB *pgxpool.Pool // for transactions
	Q  *sqlc.Queries // generated by sqlc
}

func NewStaffRepo(db *pgxpool.Pool) *StaffRepository {
	return &StaffRepository{
		DB: db,
		Q:  sqlc.New(db),
	}
}
