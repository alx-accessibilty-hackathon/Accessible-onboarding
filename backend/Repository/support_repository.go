package repository

import (
	"context"
	"time"

	domain "bridge/Domain"
	sqlc "bridge/Repository/sqlc"

	"github.com/google/uuid"
	"github.com/jackc/pgx/v5/pgxpool"
)

// SupportRepository stores support requests. Only encrypted bytes are stored.
// Table: support_requests. Queries: queries/support.sql.
type SupportRepository struct {
	DB *pgxpool.Pool // for transactions
	Q  *sqlc.Queries // generated by sqlc
}

var _ domain.SupportRepositoryI = (*SupportRepository)(nil)

func NewSupportRepo(db *pgxpool.Pool) *SupportRepository {
	return &SupportRepository{
		DB: db,
		Q:  sqlc.New(db),
	}
}

func (r *SupportRepository) Upsert(ctx context.Context, learnerID uuid.UUID, nonce, ciphertext []byte, shareCourses, shareEmployers bool) (time.Time, error) {
	updatedAt, err := r.Q.UpsertSupportRequest(ctx, sqlc.UpsertSupportRequestParams{
		LearnerID:      learnerID,
		Nonce:          nonce,
		Ciphertext:     ciphertext,
		ShareCourses:   shareCourses,
		ShareEmployers: shareEmployers,
	})
	if hasPgCode(err, pgForeignKeyViolation) {
		return time.Time{}, domain.ErrNotFound // the learner was deleted
	}
	return updatedAt, err
}

func (r *SupportRepository) Exists(ctx context.Context, learnerID uuid.UUID) (bool, error) {
	return r.Q.SupportRequestExists(ctx, learnerID)
}
