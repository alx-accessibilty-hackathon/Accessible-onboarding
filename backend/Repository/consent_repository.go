package repository

import (
	sqlc "bridge/Repository/sqlc"

	"github.com/jackc/pgx/v5/pgxpool"
)

// ConsentRepository records consents (data use, cloud speech, SMS, partner access).
// Table: consents.
type ConsentRepository struct {
	DB *pgxpool.Pool // for transactions
	Q  *sqlc.Queries // generated by sqlc
}

func NewConsentRepo(db *pgxpool.Pool) *ConsentRepository {
	return &ConsentRepository{
		DB: db,
		Q:  sqlc.New(db),
	}
}
