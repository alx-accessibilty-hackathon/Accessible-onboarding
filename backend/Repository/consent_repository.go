package repository

import (
	"context"
	"errors"

	domain "bridge/Domain"
	sqlc "bridge/Repository/sqlc"

	"github.com/google/uuid"
	"github.com/jackc/pgx/v5"
	"github.com/jackc/pgx/v5/pgxpool"
)

// ConsentRepository records consents (data use, cloud speech, SMS, partner access).
// Table: consents.
type ConsentRepository struct {
	DB *pgxpool.Pool // for transactions
	Q  *sqlc.Queries // generated by sqlc
}

var _ domain.ConsentRepositoryI = (*ConsentRepository)(nil)

func NewConsentRepo(db *pgxpool.Pool) *ConsentRepository {
	return &ConsentRepository{
		DB: db,
		Q:  sqlc.New(db),
	}
}

func (r *ConsentRepository) CreateConsent(ctx context.Context, c *domain.Consent) (*domain.Consent, error) {
	row, err := r.Q.CreateConsent(ctx, sqlc.CreateConsentParams{
		LearnerID: c.LearnerID,
		Kind:      c.Kind,
		Granted:   c.Granted,
		Method:    c.Method,
		PartnerID: c.PartnerID,
		StaffID:   c.StaffID,
	})
	if err != nil {
		return nil, err
	}

	return &domain.Consent{
		ID:        row.ID,
		LearnerID: row.LearnerID,
		Kind:      row.Kind,
		Granted:   row.Granted,
		Method:    row.Method,
		PartnerID: row.PartnerID,
		StaffID:   row.StaffID,
		CreatedAt: row.CreatedAt,
		RevokedAt: row.RevokedAt,
	}, nil
}

func (r *ConsentRepository) GetConsentByLearnerAndKind(ctx context.Context, learnerID uuid.UUID, kind string) (*domain.Consent, error) {
	row, err := r.Q.GetConsentByLearnerAndKind(ctx, sqlc.GetConsentByLearnerAndKindParams{
		LearnerID: learnerID,
		Kind:      kind,
	})
	if errors.Is(err, pgx.ErrNoRows) {
		return nil, domain.ErrNotFound
	}
	if err != nil {
		return nil, err
	}

	return &domain.Consent{
		ID:        row.ID,
		LearnerID: row.LearnerID,
		Kind:      row.Kind,
		Granted:   row.Granted,
		Method:    row.Method,
		PartnerID: row.PartnerID,
		StaffID:   row.StaffID,
		CreatedAt: row.CreatedAt,
		RevokedAt: row.RevokedAt,
	}, nil
}

func (r *ConsentRepository) ListConsentsByLearnerID(ctx context.Context, learnerID uuid.UUID) ([]*domain.Consent, error) {
	rows, err := r.Q.ListConsentsByLearnerID(ctx, learnerID)
	if err != nil {
		return nil, err
	}

	consents := make([]*domain.Consent, 0, len(rows))
	for _, row := range rows {
		consents = append(consents, &domain.Consent{
			ID:        row.ID,
			LearnerID: row.LearnerID,
			Kind:      row.Kind,
			Granted:   row.Granted,
			Method:    row.Method,
			PartnerID: row.PartnerID,
			StaffID:   row.StaffID,
			CreatedAt: row.CreatedAt,
			RevokedAt: row.RevokedAt,
		})
	}
	return consents, nil
}
